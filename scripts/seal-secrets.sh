#!/usr/bin/env bash
# Generates every runtime secret, encrypts it with the cluster's Sealed Secrets key and
# writes the SealedSecrets into Git-tracked files (safe to commit):
#
#   helm/skyforge/secrets-dev.yaml / secrets-prod.yaml    -> PostgreSQL credentials
#   argocd/platform/monitoring-secrets/grafana-admin.yaml  -> Grafana admin login
#   argocd/platform/monitoring-secrets/alertmanager-slack.yaml -> Slack webhook
#
# Requirements: kubectl + kubeseal, and `make tunnel` running in another terminal.
# Optional: SLACK_WEBHOOK_URL=https://hooks.slack.com/services/... to receive alerts.
set -euo pipefail

cd "$(dirname "$0")/.."
export KUBECONFIG="${KUBECONFIG:-$PWD/.kube/skyforge.yaml}"

KUBESEAL=(kubeseal --controller-namespace kube-system --controller-name sealed-secrets-controller --format yaml)

random_password() {
  # Alphanumeric only: the value is embedded in a database URL.
  LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 32
}

seal() { # <namespace> <name> <key=value>...
  local namespace="$1" name="$2"
  shift 2
  local args=()
  for pair in "$@"; do args+=(--from-literal="$pair"); done
  kubectl create secret generic "$name" -n "$namespace" "${args[@]}" --dry-run=client -o yaml \
    | "${KUBESEAL[@]}"
}

echo "Waiting for the Sealed Secrets controller..."
kubectl rollout status deployment/sealed-secrets-controller -n kube-system --timeout=300s

for env in ${ENVS:-dev prod}; do
  target="helm/skyforge/secrets-${env}.yaml"
  if [[ -f "$target" && "${FORCE:-false}" != "true" ]]; then
    echo "skip $target (exists; FORCE=true regenerates it, which resets the database password)"
    continue
  fi
  sealed="$(seal "skyforge-${env}" skyforge-db username=skyforge "password=$(random_password)")"
  {
    echo "# Generated by scripts/seal-secrets.sh - encrypted, safe to commit."
    echo "database:"
    echo "  sealedSecret:"
    echo "    encryptedData:"
    echo "$sealed" | sed -n '/encryptedData:/,/template:/p' | sed '1d;$d' | sed 's/^    /      /'
  } >"$target"
  echo "wrote $target"
done

monitoring_dir="argocd/platform/monitoring-secrets"
grafana_password="$(random_password)"
seal monitoring grafana-admin admin-user=admin "admin-password=${grafana_password}" \
  >"${monitoring_dir}/grafana-admin.yaml"
seal monitoring alertmanager-slack \
  "webhook-url=${SLACK_WEBHOOK_URL:-https://hooks.slack.com/services/REPLACE/ME/PLEASE}" \
  >"${monitoring_dir}/alertmanager-slack.yaml"
echo "wrote ${monitoring_dir}/{grafana-admin,alertmanager-slack}.yaml"

cat <<EOF

Grafana login: admin / ${grafana_password}   (store it in your password manager)

Next: git add helm/skyforge/secrets-*.yaml ${monitoring_dir} && git commit -m "chore: seal secrets" && git push
ArgoCD will pick the SealedSecrets up and the controller will decrypt them in-cluster.
EOF
